export function detectLocale(saved: string | null, languages: readonly string[]): Locale {
  if (saved === 'en' || saved === 'ru') return saved;
  return languages.some((language) => language.toLowerCase().startsWith('ru')) ? 'ru' : 'en';
}

export function useI18n(): { locale: Ref<Locale>; t: Translate } {
  const locale = ref<Locale>(
    detectLocale(localStorage.getItem(LOCALE_KEY), navigator.languages ?? [navigator.language]),
  );
  watch(locale, (value) => localStorage.setItem(LOCALE_KEY, value));
  return { locale, t: (key) => messages[locale.value][key] };
}
